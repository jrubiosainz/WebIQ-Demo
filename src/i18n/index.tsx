export type UIKey = keyof typeof UI;

export interface I18n {
  lang: Lang;
  t: (k: UIKey) => string;
  tl: (x: L) => string;
}

export const makeI18n = (lang: Lang): I18n => ({
  lang,
  t: (k) => UI[k][lang],
  tl: (x) => x[lang],
});

export const I18nContext = createContext<I18n>(makeI18n('es'));
export const useI18n = () => useContext(I18nContext);
